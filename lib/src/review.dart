import 'engine.dart';
import 'game.dart';
import 'game_record.dart';
import 'position.dart';
import 'side.dart';

/// How good a move was, judged by the eval swing it caused — generalizes
/// komovia_chess's own `MoveQuality` (best/good/inaccuracy/mistake/blunder,
/// classified from centipawn-loss thresholds 15/50/100/300) so a shared
/// post-game review feature doesn't need to be reinvented per game.
enum MoveQuality { best, good, inaccuracy, mistake, blunder }

/// Classifies [loss] (always >= 0 — how much worse [Engine.evaluate] rated
/// the position, from the mover's own perspective, after the move than
/// before it) into a [MoveQuality] using komovia_chess's thresholds.
///
/// A free function rather than a method on [MoveAnalysis] so a caller that
/// already has a loss value from elsewhere (e.g. a cached analysis) can
/// classify it without constructing a whole [MoveAnalysis].
MoveQuality classifyMoveQuality(double loss) {
  if (loss >= 300) return MoveQuality.blunder;
  if (loss >= 100) return MoveQuality.mistake;
  if (loss >= 50) return MoveQuality.inaccuracy;
  if (loss >= 15) return MoveQuality.good;
  return MoveQuality.best;
}

/// One played move, with the engine's before/after evaluation of the
/// position and the resulting judgment.
class MoveAnalysis {
  final int moveIndex;
  final Side side;

  /// [Engine.evaluate]'s result before the move, fixed to [Side.first]'s
  /// perspective (same convention as [Engine.evaluate] itself).
  final double evalBefore;

  /// [Engine.evaluate]'s result after the move, same perspective.
  final double evalAfter;

  /// How much worse the position got for [side] specifically — always
  /// >= 0. Computed from [evalBefore]/[evalAfter] by flipping sign for
  /// [Side.second] (whose gain is [Side.first]'s loss), then clamped to
  /// >= 0 since an engine's own move should never *increase* its mover's
  /// loss relative to the best available move — a negative raw swing
  /// means the mover improved their own position.
  final double loss;

  final MoveQuality quality;

  const MoveAnalysis({
    required this.moveIndex,
    required this.side,
    required this.evalBefore,
    required this.evalAfter,
    required this.loss,
    required this.quality,
  });
}

/// A complete post-game review: every move judged against the engine, plus
/// a per-side accuracy summary — generalizes komovia_chess's own
/// `GameAnalysis`/`ChessAnalysisService` (deliberately *not* komovia_go's
/// differently-shaped, LLM/Cloud-Function-backed `GameAnalysis` — see
/// [ReviewEngine]'s doc comment for why).
class GameAnalysis {
  final List<MoveAnalysis> moves;

  const GameAnalysis({required this.moves});

  List<MoveAnalysis> movesBy(Side side) =>
      moves.where((m) => m.side == side).toList();

  List<MoveAnalysis> get blunders =>
      moves.where((m) => m.quality == MoveQuality.blunder).toList();

  List<MoveAnalysis> get mistakes =>
      moves.where((m) => m.quality == MoveQuality.mistake).toList();

  /// Percentage (0-100) of [side]'s own moves judged [MoveQuality.best] or
  /// [MoveQuality.good]. Returns 100 if [side] made no moves at all (an
  /// empty game has nothing to be inaccurate about).
  double accuracyFor(Side side) {
    final own = movesBy(side);
    if (own.isEmpty) return 100;
    final goodOrBest = own
        .where((m) =>
            m.quality == MoveQuality.best || m.quality == MoveQuality.good)
        .length;
    return goodOrBest / own.length * 100;
  }
}

/// Produces a [GameAnalysis] for a finished [GameRecord] — the shared
/// shape behind komovia_chess's `ChessAnalysisService`/`GameReviewScreen`
/// (real, engine-based, reachable from several real screens there) so the
/// other sibling apps can get the same post-game review for free once they
/// have an [Engine].
///
/// Deliberately *not* modeled on komovia_go's `AIExplanationService`/
/// `GameAnalysis` (prose `MoveExplanation`s generated by a Cloud Function,
/// i.e. an LLM-shaped commentary feature) — that is a heavier, optional,
/// natural-language layer an app may add *on top of* a [ReviewEngine]'s
/// numeric judgment, not a substitute for it, and the two `GameAnalysis`
/// names already collide across komovia_go/komovia_chess the same way
/// `NotificationSeverity`/`AppNotification` do elsewhere in this family —
/// this interface claims the engine-eval shape; an LLM-commentary
/// counterpart should be named differently if/when it's shared.
abstract interface class ReviewEngine<P extends Position> {
  Future<GameAnalysis> analyzeGame(
    GameRecord record,
    P initialPosition, {
    void Function(int done, int total)? onProgress,
  });
}

/// A [ReviewEngine] implemented purely in terms of an existing
/// [Game]/[Engine] pair — any sibling app that already has an [Engine] for
/// its game gets post-game review for free, with no extra per-game code.
///
/// Replays [GameRecord.moves] one at a time through [Game.apply], calling
/// [Engine.evaluate] before and after each move. [Engine.evaluate] is
/// fixed to [Side.first]'s perspective regardless of who moved (see its
/// own doc comment), so the swing is negated for [Side.second] before
/// being reported as that side's [MoveAnalysis.loss] — a mover's own loss
/// should read as non-negative board-agnostic "how much worse for the
/// player who just moved", not as a sign flip a caller has to redo.
class EngineReviewEngine<P extends Position> implements ReviewEngine<P> {
  final Game<P> game;
  final Engine<P> engine;

  const EngineReviewEngine({required this.game, required this.engine});

  @override
  Future<GameAnalysis> analyzeGame(
    GameRecord record,
    P initialPosition, {
    void Function(int done, int total)? onProgress,
  }) async {
    final moves = <MoveAnalysis>[];
    var position = initialPosition;
    var evalBefore = await engine.evaluate(position);
    final total = record.moves.length;

    for (final recorded in record.moves) {
      position = game.apply(position, recorded.move);
      final evalAfter = await engine.evaluate(position);

      final rawSwing = recorded.side == Side.first
          ? evalBefore - evalAfter
          : evalAfter - evalBefore;
      final loss = rawSwing < 0 ? 0.0 : rawSwing;

      moves.add(MoveAnalysis(
        moveIndex: recorded.number,
        side: recorded.side,
        evalBefore: evalBefore,
        evalAfter: evalAfter,
        loss: loss,
        quality: classifyMoveQuality(loss),
      ));

      onProgress?.call(moves.length, total);
      evalBefore = evalAfter;
    }

    return GameAnalysis(moves: moves);
  }
}
